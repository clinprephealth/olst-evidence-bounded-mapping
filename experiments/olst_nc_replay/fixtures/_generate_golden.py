"""Write golden_output_hashes_<version>.json for the synthetic fixture suite.

Usage (from repo root)::

    PYTHONPATH=. python -m experiments.olst_nc_replay.fixtures._generate_golden --mapping-spec-version v2

Refuses to overwrite an existing golden file unless ``--force`` is given: a
golden file is a frozen artifact, and regenerating it silently would defeat
its purpose. The v1 golden file was written by hand at commit 7dba0546 and is
never regenerated by this script.
"""

from __future__ import annotations

import argparse
import json
import sys
import warnings
from pathlib import Path

from experiments.olst_nc_replay import ExcludedCaptureError, run

_HERE = Path(__file__).resolve().parent


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mapping-spec-version", required=True)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    version = args.mapping_spec_version
    if version == "v1":
        print("refusing: v1 golden file is frozen and hand-written.", file=sys.stderr)
        return 2
    out = _HERE / f"golden_output_hashes_{version}.json"
    if out.exists() and not args.force:
        print(f"refusing: {out.name} exists (use --force to regenerate deliberately).", file=sys.stderr)
        return 2

    golden: dict[str, dict] = {}
    for fp in sorted(_HERE.glob("*.json")):
        if fp.name.startswith("golden_output_hashes_"):
            continue
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", UserWarning)
                rep = run(fp, mapping_spec_version=version)
        except ExcludedCaptureError as e:
            golden[fp.name] = {
                "expects_exception": "ExcludedCaptureError",
                "fixture_id": None,
                "output_hash": None,
                "note": str(e)[:160],
            }
            continue
        golden[fp.name] = {
            "expects_exception": None,
            "fixture_id": rep.fixture_id,
            "output_hash": rep.output_hash,
        }
    out.write_text(json.dumps(golden, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(golden)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
